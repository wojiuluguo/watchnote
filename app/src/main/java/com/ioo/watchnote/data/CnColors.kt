/* ============================================================
   按主色系分页：一个色系一页（红归红、绿归绿），
   同一页里不再混别的色相，也不会切成一堆小碎片。
   ============================================================ */

val CN_SERIES: List<CnFamily> = CN_FAMILIES

/** 当前强调色属于哪个细分系列；不是中国传统色时返回 -1。 */
fun cnSeriesIndexOf(argb: Int): Int {
    if (argb == 0) return -1
    val v = argb.toLong() and 0xFFFFFFFFL
    return CN_SERIES.indexOfFirst { fam -> fam.colors.any { it.argb == v } }
}

/** 当前强调色对应的中国传统色名；找不到返回 null。 */
fun cnColorNameOf(argb: Int): String? {
    if (argb == 0) return null
    val v = argb.toLong() and 0xFFFFFFFFL
    CN_FAMILIES.forEach { fam ->
        fam.colors.firstOrNull { it.argb == v }?.let { return it.name }
    }
    return null
}

